import assert from "node:assert/strict";
import { test } from "node:test";
import {
	classifyGomobileFailure,
	checkBindingSurface,
	EXPORTED_FUNCTIONS,
	expectedSymbols,
	lowerFirst,
	parseExportedFunctions,
	parseJavaMethods,
	parseObjcExports,
	parseSkippedFunctions,
	parseTargets,
	wantsSurfaceOnly,
} from "./mobile-bind-proxyrules.mjs";

const IOS_NO_XCODE = 'gomobile: -target="ios" requires Xcode\n';

const ANDROID_NO_SDK =
	"gomobile: could not locate Android SDK: stat /Users/noelorin/Library/Android/sdk: no such file or directory; Android SDK was not found at /Users/noelorin/Library/Android/sdk\n";

const ANDROID_NO_NDK =
	"gomobile: could not locate Android NDK: stat /Users/noelorin/Library/Android/sdk/ndk: no such file or directory; Android NDK was not found in the Android SDK\n";

const ANDROID_NDK_API_MISMATCH =
	"gomobile: ANDROID_NDK_HOME specifies /usr/local/lib/android/sdk/ndk/27.3.13750724, which is unusable: unsupported API version 16 (not in 21..35)\n";

const ANDROID_NO_JAVAC =
	'gomobile: exec: "javac": executable file not found in $PATH\n';

const GENUINE_FAILURE =
	"# gospeak/proxyrules\n./proxyrules.go:12:5: undefined: stringsx\ngomobile: go build failed\n";

const OBJC_HEADER = [
	"// Objective-C API for talking to gospeak/proxyrules Go package.",
	"// File is generated by gobind. Do not edit.",
	"",
	"#ifndef __Proxyrules_H__",
	"#define __Proxyrules_H__",
	"",
	"FOUNDATION_EXPORT BOOL ProxyrulesIsTrustedWorker(NSString* _Nullable target, NSString* _Nullable baseURL, NSString* _Nullable allowed);",
	"",
	"FOUNDATION_EXPORT NSString* _Nonnull ProxyrulesNormalizeBaseURL(NSString* _Nullable raw);",
	"",
	"FOUNDATION_EXPORT NSString* _Nonnull ProxyrulesNormalizedHostPort(NSString* _Nullable scheme, NSString* _Nullable hostport, NSError* _Nullable* _Nullable error);",
	"",
	"FOUNDATION_EXPORT NSString* _Nonnull ProxyrulesRewriteSetCookie(NSString* _Nullable value);",
	"",
	"FOUNDATION_EXPORT BOOL ProxyrulesValidateBaseURL(NSString* _Nullable raw, NSError* _Nullable* _Nullable error);",
	"",
	"#endif",
	"",
].join("\n");

const USER_SESSION_HEADER = [
	"FOUNDATION_EXPORT BOOL SkipkAlsoGood(NSString* _Nullable a, NSString* _Nullable b);",
	"// skipped function Bad with unsupported parameter or return types",
	"FOUNDATION_EXPORT BOOL SkipkGood(NSString* _Nullable raw, NSError* _Nullable* _Nullable error);",
	"",
].join("\n");

const JAVA_BINDING = [
	"// Code generated by gobind. DO NOT EDIT.",
	"package proxyrules;",
	"",
	"public abstract class Proxyrules {",
	"\tprivate static native void _init();",
	"",
	"\tpublic static native boolean isTrustedWorker(String target, String baseURL, String allowed);",
	"\tpublic static native String normalizeBaseURL(String raw);",
	"\tpublic static native String normalizedHostPort(String scheme, String hostport) throws Exception;",
	"\tpublic static native String rewriteSetCookie(String value);",
	"\tpublic static native void validateBaseURL(String raw) throws Exception;",
	"}",
	"",
].join("\n");

const GO_SOURCE = [
	"package proxyrules",
	"",
	"func ValidateBaseURL(raw string) error { return nil }",
	"",
	"func NormalizeBaseURL(raw string) string { return raw }",
	"",
	"func RewriteSetCookie(value string) string { return value }",
	"",
	"func IsTrustedWorker(target, baseURL, allowed string) bool { return false }",
	"",
	'func NormalizedHostPort(scheme, hostport string) (string, error) { return "", nil }',
	"",
	"func helper() {}",
	"",
].join("\n");

test("classifyGomobileFailure treats missing Xcode as an environment gap", () => {
	const verdict = classifyGomobileFailure(IOS_NO_XCODE, "ios");
	assert.equal(verdict.kind, "environment-missing");
	assert.equal(verdict.id, "xcode");
	assert.ok(verdict.nextSteps.length > 0);
});

test("classifyGomobileFailure treats a missing Android SDK as an environment gap", () => {
	const verdict = classifyGomobileFailure(ANDROID_NO_SDK, "android");
	assert.equal(verdict.kind, "environment-missing");
	assert.equal(verdict.id, "android-sdk");
	assert.match(verdict.summary, /Android SDK/);
});

test("classifyGomobileFailure treats a missing Android NDK as an environment gap", () => {
	const verdict = classifyGomobileFailure(ANDROID_NO_NDK, "android");
	assert.equal(verdict.kind, "environment-missing");
	assert.equal(verdict.id, "android-ndk");
});

test("classifyGomobileFailure treats an unusable NDK API level as an environment gap", () => {
	const verdict = classifyGomobileFailure(ANDROID_NDK_API_MISMATCH, "android");
	assert.equal(verdict.kind, "environment-missing");
	assert.equal(verdict.id, "android-ndk");
});

test("classifyGomobileFailure treats a missing JDK as an environment gap", () => {
	const verdict = classifyGomobileFailure(ANDROID_NO_JAVAC, "android");
	assert.equal(verdict.kind, "environment-missing");
	assert.equal(verdict.id, "java");
});

test("classifyGomobileFailure keeps real build failures fatal", () => {
	const verdict = classifyGomobileFailure(GENUINE_FAILURE, "android");
	assert.equal(verdict.kind, "failure");
	assert.equal(verdict.id, "unknown");
	assert.deepEqual(verdict.nextSteps, []);
});

test("classifyGomobileFailure ignores another platform's environment error", () => {
	const verdict = classifyGomobileFailure(IOS_NO_XCODE, "android");
	assert.equal(verdict.kind, "failure");
});

test("classifyGomobileFailure reports empty output instead of throwing", () => {
	const verdict = classifyGomobileFailure("", "ios");
	assert.equal(verdict.kind, "failure");
	assert.equal(verdict.detail, "(无输出)");
});

test("parseObjcExports strips the package prefix", () => {
	assert.deepEqual(
		[...parseObjcExports(OBJC_HEADER)].sort(),
		[...EXPORTED_FUNCTIONS].sort(),
	);
});

test("parseObjcExports keeps raw symbols when no prefix is given", () => {
	const names = parseObjcExports(USER_SESSION_HEADER, "");
	assert.deepEqual([...names].sort(), ["SkipkAlsoGood", "SkipkGood"]);
	assert.equal(names.has("Bad"), false);
});

test("parseJavaMethods collects public static native methods", () => {
	const methods = parseJavaMethods(JAVA_BINDING);
	assert.deepEqual([...methods].sort(), [
		"isTrustedWorker",
		"normalizeBaseURL",
		"normalizedHostPort",
		"rewriteSetCookie",
		"validateBaseURL",
	]);
	assert.equal(methods.has("_init"), false);
});

test("parseSkippedFunctions extracts silently skipped names", () => {
	assert.deepEqual(parseSkippedFunctions(USER_SESSION_HEADER), ["Bad"]);
	assert.deepEqual(parseSkippedFunctions(OBJC_HEADER), []);
	assert.deepEqual(
		parseSkippedFunctions(
			"\t// skipped function Bad with unsupported parameter or return types",
		),
		["Bad"],
	);
});

test("expectedSymbols lowercases the first letter for java only", () => {
	assert.deepEqual(expectedSymbols(["ValidateBaseURL"], "java"), [
		"validateBaseURL",
	]);
	assert.deepEqual(expectedSymbols(["ValidateBaseURL"], "objc"), [
		"ValidateBaseURL",
	]);
	assert.equal(lowerFirst("IsTrustedWorker"), "isTrustedWorker");
	assert.equal(lowerFirst(""), "");
});

test("checkBindingSurface passes when every exported function is bound", () => {
	const objc = checkBindingSurface({
		exports: parseObjcExports(OBJC_HEADER),
		lang: "objc",
	});
	const java = checkBindingSurface({
		exports: parseJavaMethods(JAVA_BINDING),
		lang: "java",
	});
	assert.equal(objc.ok, true);
	assert.equal(java.ok, true);
	assert.deepEqual(objc.missing, []);
});

test("checkBindingSurface fails when a function was never bound", () => {
	const header = OBJC_HEADER.replace(
		/^FOUNDATION_EXPORT BOOL ProxyrulesValidateBaseURL.*$/m,
		"",
	);
	const result = checkBindingSurface({
		exports: parseObjcExports(header),
		lang: "objc",
	});
	assert.equal(result.ok, false);
	assert.deepEqual(result.missing, ["ValidateBaseURL"]);
});

test("parseExportedFunctions reads top-level exported functions only", () => {
	assert.deepEqual(
		[...parseExportedFunctions(GO_SOURCE)].sort(),
		[...EXPORTED_FUNCTIONS].sort(),
	);
});

test("wantsSurfaceOnly is opt-in and ignores the target flag", () => {
	assert.equal(wantsSurfaceOnly([]), false);
	assert.equal(wantsSurfaceOnly(["--target=all"]), false);
	assert.equal(wantsSurfaceOnly(["--surface-only"]), true);
	assert.equal(wantsSurfaceOnly(["--target=all", "--surface-only"]), true);
});

test("parseTargets defaults to both platforms and validates the value", () => {
	assert.deepEqual(parseTargets([]), ["ios", "android"]);
	assert.deepEqual(parseTargets(["--target=all"]), ["ios", "android"]);
	assert.deepEqual(parseTargets(["--target=android"]), ["android"]);
	assert.throws(() => parseTargets(["--target=desktop"]), /未知的 --target/);
});
